    def test_content_hash_deterministic(self):
        """Same payload always produces the same hash."""
        payload = {"key": "value", "nested": {"a": 1}}
        h1 = content_hash(payload)
        h2 = content_hash(payload)
        assert h1 == h2
        # Different key order → same canonical JSON → same hash
        h3 = content_hash({"nested": {"a": 1}, "key": "value"})
        assert h1 == h3

    def test_unchanged_source_stored_once(self):
        """Importing the same content twice does not create a second revision."""
        fixture = load_fixture("cve_published.json")
        with get_db_connection() as conn:
            upsert_canonical_vulnerability(conn, CanonicalVulnerability(
                cve_id="CVE-2024-1234", state="PUBLISHED"))

            rec1, is_new1 = upsert_source_record(conn, SourceRecord(
                source="cve", source_id="CVE-2024-1234",
                cve_id="CVE-2024-1234", raw_payload=fixture,
            ))
            conn.commit()

            rec2, is_new2 = upsert_source_record(conn, SourceRecord(
                source="cve", source_id="CVE-2024-1234",
                cve_id="CVE-2024-1234", raw_payload=fixture,
            ))
            conn.commit()

            assert is_new1 is True
            assert is_new2 is False  # Deduped — same content hash
            assert rec1.content_hash == rec2.content_hash

            revisions = get_source_record_revisions(conn, "cve", "CVE-2024-1234")
            assert len(revisions) == 1  # Only one revision stored

    def test_new_content_creates_revision_moves_current(self):
        """Changed content creates a new revision and moves is_current."""
        fixture_v1 = load_fixture("cve_published.json")
        fixture_v2 = load_fixture("cve_published_updated.json")
        with get_db_connection() as conn:
            upsert_canonical_vulnerability(conn, CanonicalVulnerability(
                cve_id="CVE-2024-1234", state="PUBLISHED"))

            rec1, _ = upsert_source_record(conn, SourceRecord(
                source="cve", source_id="CVE-2024-1234",
                cve_id="CVE-2024-1234", raw_payload=fixture_v1,
            ))
            conn.commit()
            assert rec1.is_current is True

            rec2, is_new = upsert_source_record(conn, SourceRecord(
                source="cve", source_id="CVE-2024-1234",
                cve_id="CVE-2024-1234", raw_payload=fixture_v2,
            ))
            conn.commit()
            assert is_new is True
            assert rec1.content_hash != rec2.content_hash

            # Current pointer moved
            current = get_current_source_record(conn, "cve", "CVE-2024-1234")
            assert current is not None
            assert current.content_hash == rec2.content_hash

            # Prior revision traceable
            revisions = get_source_record_revisions(conn, "cve", "CVE-2024-1234")
            assert len(revisions) == 2
            assert revisions[0].is_current is True   # newest first
            assert revisions[1].is_current is False

    def test_snapshot_lifecycle(self):
        """Sync snapshots record provenance and activation."""
        with get_db_connection() as conn:
            snap = create_sync_snapshot(conn, SyncSnapshot(
                source="cve", sync_mode="bootstrap",
                cursor_before=None,
            ))
            conn.commit()

            assert snap.id is not None
            assert snap.status == "running"

