class TestCveIdValidation:
    """CVE IDs are syntax-validated and never generated by Tempris."""

    def test_valid_cve_ids(self):
        assert validate_cve_id("CVE-2024-1234") is True
        assert validate_cve_id("CVE-1999-0001") is True
        assert validate_cve_id("CVE-2024-12345678") is True  # 8-digit seq OK

    def test_invalid_cve_ids(self):
        assert validate_cve_id("CVE-INVALID") is False
        assert validate_cve_id("CVE-2024-123") is False      # too short seq
        assert validate_cve_id("cve-2024-1234") is False     # lowercase
        assert validate_cve_id("CVE-24-1234") is False       # 2-digit year
        assert validate_cve_id("") is False
        assert validate_cve_id("GHSA-xxxx-yyyy-zzzz") is False
        assert validate_cve_id("CVE2024-1234") is False      # missing dash

    def test_malformed_cve_fixture_rejected(self):
        fixture = load_fixture("cve_malformed.json")
        cve_id = fixture["cveMetadata"]["cveId"]
        assert validate_cve_id(cve_id) is False


